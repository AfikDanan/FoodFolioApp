export async function seedSampleData() {
  const categories = (await fetchAllCategories()) || [];
  const idOf = (name) => categories.find((c) => c.name === name)?.id;
  const ids = [];
  for (const [title, category, minutes, servings, tags, fridgeDays, ingredients, steps] of RECIPES) {
    ids.push(
      await insertRecipeWithCategories({
        title,
        ingredients,
        instructions: stepsToObject(steps),
        totalTime: `${minutes} דקות`,
        servings,
        tags,
        fridgeDays,
        categoryIds: idOf(category) ? [idOf(category)] : [],
      })
    );
  }
  const today = new Date();
  const tomorrow = new Date(today.getFullYear(), today.getMonth(), today.getDate() + 1);
  await savePlan({
    [slotKey(today, "בוקר")]: ids[0],
    [slotKey(today, "ערב")]: ids[1],
    [slotKey(tomorrow, "צהריים")]: ids[3],
  });
  return { added: ids.length };
}
